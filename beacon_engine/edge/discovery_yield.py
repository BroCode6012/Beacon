"""Committed search attribution in the existing signed import ledger.

Counts stay integer-valued for ACK/transport compatibility. Query identity is a
JSON array in each metric key, so labels need no additional table or index copy.
When searches overlap, the earliest completed matching search gets one credit.
This is recorded provenance, not a claim about an isolated search's causal yield.
"""
from __future__ import annotations

import datetime as dt
import json
from typing import Any

from beacon_engine.edge.protocol import EdgeProtocolError

PREFIXES = {"successful_searches": "yield_ok:", "failed_searches": "yield_error:",
            "new_channels": "yield_new:", "existing_channel_matches": "yield_existing:"}
MAX_REPORT_BUNDLES = 2048


def query_identity(row: dict[str, Any]) -> str:
    return json.dumps([str(row.get(name) or "") for name in
                       ("query", "topic", "provider", "sort")],
                      ensure_ascii=True, separators=(",", ":"))


def attribution_counts(records: dict, new_ids: set[str]) -> dict[str, int]:
    runs = records.get("query_runs", [])
    if not any("channel_ids" in row for row in runs):
        return {}  # Old signed bundles remain valid and are explicitly unmeasured.
    parents = {str(row.get("channel_id") or "") for row in records.get("channels", [])}
    counts: dict[str, int] = {"query_yield_version": 1}
    credited: set[str] = set()
    complete = True
    # Completion timestamps are generated by the collector in normalized UTC.
    for row in sorted(runs, key=lambda r: (str(r.get("finished_at") or ""), query_identity(r))):
        if "channel_ids" not in row:
            complete = False
            continue
        ids = row["channel_ids"]
        if (not isinstance(ids, list) or len(ids) > 200
                or any(not isinstance(cid, str) or not cid or cid not in parents for cid in ids)):
            raise EdgeProtocolError("query channel provenance must reference at most 200 bundle channels")
        channels = set(ids)
        identity = query_identity(row)
        if row.get("status") != "ok":
            if channels:
                raise EdgeProtocolError("failed searches cannot claim channel provenance")
            key = PREFIXES["failed_searches"] + identity
            counts[key] = counts.get(key, 0) + 1
            continue
        observed_new = channels & new_ids
        first_new = observed_new - credited
        credited.update(first_new)
        for field, value in (("successful_searches", 1), ("new_channels", len(first_new)),
                             ("existing_channel_matches", len(channels - new_ids))):
            key = PREFIXES[field] + identity
            counts[key] = counts.get(key, 0) + value
    counts.update({"query_yield_complete": int(complete),
                   "channels_new_attributed": len(credited),
                   "channels_new_unattributed": len(new_ids - credited)})
    return counts


def discovery_yield_report(store, *, hours: int = 24, limit: int = 50,
                           minimum_searches: int = 3) -> dict[str, Any]:
    """Bounded read-only evidence; incomplete history never becomes a zero yield."""
    hours, limit, minimum_searches = int(hours), int(limit), int(minimum_searches)
    if not 1 <= hours <= 168 or not 1 <= limit <= 100 or not 1 <= minimum_searches <= 1000:
        raise ValueError("Use hours 1-168, limit 1-100, and minimum_searches 1-1000")
    cutoff = (dt.datetime.now(dt.timezone.utc) - dt.timedelta(hours=hours)).isoformat().replace("+00:00", "Z")
    conn = None
    try:
        conn = store.connect()
        rows = conn.execute(
            "SELECT imported_at, counts_json FROM edge_import_batches "
            "WHERE kind=? AND imported_at>=? ORDER BY imported_at DESC LIMIT ?",
            ("youtube.discovery.v1", cutoff, MAX_REPORT_BUNDLES + 1),
        ).fetchall()
    except Exception as exc:
        if ((type(exc).__name__ == "OperationalError" and "no such table" in str(exc))
                or type(exc).__name__ == "UndefinedTable"):
            rows = []
        else:
            raise RuntimeError("Could not read discovery yield; retry when the index is available") from None
    finally:
        if conn is not None:
            conn.close()
    truncated = len(rows) > MAX_REPORT_BUNDLES
    totals = {"counted_new_channels": 0, "attributed_new_channels": 0,
              "successful_searches": 0, "failed_searches": 0}
    measured, historical, incomplete, corrupt = 0, 0, 0, 0
    first, last = "", ""
    queries: dict[str, dict[str, Any]] = {}
    for row in rows[:MAX_REPORT_BUNDLES]:
        try:
            counts = json.loads(row[1])
            if not isinstance(counts, dict) or any(type(v) is not int or v < 0 for v in counts.values()):
                raise ValueError("invalid counts")
            parsed = []
            if counts.get("query_yield_version") == 1 and counts.get("query_yield_complete") == 1:
                for key, value in counts.items():
                    for field, prefix in PREFIXES.items():
                        if key.startswith(prefix):
                            identity = key[len(prefix):]
                            labels = json.loads(identity)
                            if not isinstance(labels, list) or len(labels) != 4 or any(not isinstance(v, str) for v in labels):
                                raise ValueError("invalid query identity")
                            parsed.append((identity, labels, field, value))
                attributed = sum(value for _, _, field, value in parsed if field == "new_channels")
                if attributed != counts.get("channels_new_attributed", 0) or attributed > counts.get("channels_new", 0):
                    raise ValueError("invalid attribution total")
        except (ValueError, TypeError, AttributeError):
            corrupt += 1
            continue
        totals["counted_new_channels"] += counts.get("channels_new", 0)
        if counts.get("query_yield_version") != 1:
            historical += 1
            continue
        if counts.get("query_yield_complete") != 1:
            incomplete += 1
            continue
        measured += 1
        first = min(first or row[0], row[0]); last = max(last, row[0])
        totals["attributed_new_channels"] += counts.get("channels_new_attributed", 0)
        for identity, labels, field, value in parsed:
            item = queries.setdefault(identity, {
                **dict(zip(("query", "topic", "provider", "sort"), labels)),
                **dict.fromkeys(PREFIXES, 0),
            })
            item[field] += value
            if field in ("successful_searches", "failed_searches"):
                totals[field] += value
    eligible = []
    for item in queries.values():
        searches = item["successful_searches"]
        if searches < minimum_searches:
            continue
        item["new_channels_per_1000_searches"] = round(item["new_channels"] * 1000 / searches, 2)
        eligible.append(item)
    eligible.sort(key=lambda item: (-item["new_channels_per_1000_searches"], -item["successful_searches"], item["query"], item["topic"], item["provider"], item["sort"]))
    return {
        "status": "measured" if eligible else "collecting",
        "hours": hours, "minimum_searches": minimum_searches,
        "first_measured_import": first, "last_measured_import": last,
        "measured_bundles": measured, "historical_bundles_without_provenance": historical,
        "incomplete_bundles": incomplete, "unreadable_bundles": corrupt,
        "truncated": truncated, **totals,
        "unattributed_new_channels": totals["counted_new_channels"] - totals["attributed_new_channels"],
        "queries_below_minimum": sum(item["successful_searches"] < minimum_searches for item in queries.values()),
        "eligible_queries": len(eligible), "queries": eligible[:limit],
        "attribution": "One credit per inserted channel to its earliest completed matching search in that bundle; overlap is not counted twice. This is recorded provenance, not isolated causal yield.",
    }
